-- ---------- 3 TRIGGERS ----------

-- Trigger 1: Do not allow fertilizer usage when stock is insufficient.
CREATE OR REPLACE FUNCTION check_fertilizer_stock()
RETURNS TRIGGER AS $$
DECLARE
    available NUMERIC(10,2);
BEGIN
    SELECT stock_level INTO available
    FROM fertilizer
    WHERE fertilizer_id = NEW.fertilizer_id
    FOR UPDATE;

    IF available < NEW.quantity_used THEN
        RAISE EXCEPTION 'Insufficient fertilizer stock.';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_check_fertilizer_stock
BEFORE INSERT ON fertilizer_usage
FOR EACH ROW EXECUTE FUNCTION check_fertilizer_stock();

-- Trigger 2: Automatically reduce fertilizer stock after usage.
CREATE OR REPLACE FUNCTION reduce_fertilizer_stock()
RETURNS TRIGGER AS $$
BEGIN
    UPDATE fertilizer
    SET stock_level = stock_level - NEW.quantity_used
    WHERE fertilizer_id = NEW.fertilizer_id;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_reduce_fertilizer_stock
AFTER INSERT ON fertilizer_usage
FOR EACH ROW EXECUTE FUNCTION reduce_fertilizer_stock();

-- Trigger 3: Prevent equipment under maintenance from being assigned.
CREATE OR REPLACE FUNCTION prevent_maintenance_equipment_assignment()
RETURNS TRIGGER AS $$
DECLARE
    current_status VARCHAR(20);
BEGIN
    SELECT status INTO current_status
    FROM equipment
    WHERE equipment_id = NEW.equipment_id;

    IF current_status = 'Under Maintenance' THEN
        RAISE EXCEPTION 'Equipment is under maintenance and cannot be assigned.';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_prevent_maintenance_assignment
BEFORE INSERT ON equipment_assignment
FOR EACH ROW EXECUTE FUNCTION prevent_maintenance_equipment_assignment();

-- Trigger 4: Prevent selling more than the available harvested quantity.
CREATE OR REPLACE FUNCTION check_sale_quantity()
RETURNS TRIGGER AS $$
DECLARE
    remaining NUMERIC(12,2);
BEGIN
    SELECT h.quantity - COALESCE(SUM(si.quantity_sold),0)
    INTO remaining
    FROM harvest h
    LEFT JOIN sale_item si ON si.harvest_id = h.harvest_id
    WHERE h.harvest_id = NEW.harvest_id
    GROUP BY h.quantity;

    IF NEW.quantity_sold > COALESCE(remaining,0) THEN
        RAISE EXCEPTION 'Quantity sold cannot exceed available harvested quantity.';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_check_sale_quantity
BEFORE INSERT ON sale_item
FOR EACH ROW EXECUTE FUNCTION check_sale_quantity();

-- ---------- 2 USER-DEFINED FUNCTIONS ----------

CREATE OR REPLACE FUNCTION get_customer_total_sales(p_customer_id INTEGER)
RETURNS NUMERIC(12,2) AS $$
DECLARE
    total_sales NUMERIC(12,2);
BEGIN
    SELECT COALESCE(SUM(total_amount),0)
    INTO total_sales
    FROM sale
    WHERE customer_id = p_customer_id;

    RETURN total_sales;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION get_remaining_harvest(p_harvest_id INTEGER)
RETURNS NUMERIC(12,2) AS $$
DECLARE
    harvested NUMERIC(12,2);
    sold NUMERIC(12,2);
BEGIN
    SELECT quantity INTO harvested
    FROM harvest
    WHERE harvest_id = p_harvest_id;

    SELECT COALESCE(SUM(quantity_sold),0)
    INTO sold
    FROM sale_item
    WHERE harvest_id = p_harvest_id;

    RETURN harvested - sold;
END;
$$ LANGUAGE plpgsql;

-- ---------- 3 STORED PROCEDURES ----------

CREATE OR REPLACE PROCEDURE record_harvest(
    p_crop_id INTEGER,
    p_harvest_date DATE,
    p_quantity NUMERIC(10,2)
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_quantity <= 0 THEN
        RAISE EXCEPTION 'Harvest quantity must be greater than zero.';
    END IF;

    INSERT INTO harvest(crop_id, harvest_date, quantity)
    VALUES(p_crop_id, p_harvest_date, p_quantity);
END;
$$;

CREATE OR REPLACE PROCEDURE use_fertilizer(
    p_fertilizer_id INTEGER,
    p_crop_id INTEGER,
    p_quantity NUMERIC(10,2),
    p_usage_date DATE
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_quantity <= 0 THEN
        RAISE EXCEPTION 'Fertilizer quantity must be greater than zero.';
    END IF;

    INSERT INTO fertilizer_usage(fertilizer_id, crop_id, quantity_used, usage_date)
    VALUES(p_fertilizer_id, p_crop_id, p_quantity, p_usage_date);
END;
$$;

CREATE OR REPLACE PROCEDURE record_sale(
    p_customer_id INTEGER,
    p_harvest_id INTEGER,
    p_quantity NUMERIC(10,2),
    p_unit_price NUMERIC(12,2),
    p_sale_date DATE
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_sale_id INTEGER;
    v_remaining NUMERIC(12,2);
    v_invoice VARCHAR(30);
BEGIN
    IF p_quantity <= 0 OR p_unit_price < 0 THEN
        RAISE EXCEPTION 'Invalid sale quantity or unit price.';
    END IF;

    v_remaining := get_remaining_harvest(p_harvest_id);

    IF p_quantity > v_remaining THEN
        RAISE EXCEPTION 'Sale quantity exceeds available harvested quantity.';
    END IF;

    INSERT INTO sale(customer_id, sale_date, invoice_number, total_amount)
    VALUES(
        p_customer_id,
        p_sale_date,
        'AUTO-' || TO_CHAR(CURRENT_TIMESTAMP,'YYYYMMDDHH24MISSMS'),
        p_quantity * p_unit_price
    )
    RETURNING sale_id, invoice_number INTO v_sale_id, v_invoice;

    INSERT INTO sale_item(sale_id, harvest_id, quantity_sold, unit_price)
    VALUES(v_sale_id, p_harvest_id, p_quantity, p_unit_price);
END;
$$;

-- ---------- 5 VIEWS ----------

CREATE OR REPLACE VIEW crop_production_view AS
SELECT
    c.crop_id,
    c.crop_type,
    c.plot_number,
    c.status,
    COALESCE(SUM(h.quantity),0) AS total_harvested
FROM crop c
LEFT JOIN harvest h ON h.crop_id = c.crop_id
GROUP BY c.crop_id, c.crop_type, c.plot_number, c.status;

CREATE OR REPLACE VIEW worker_crop_view AS
SELECT
    w.worker_id,
    w.employee_id,
    w.fname || ' ' || w.lname AS worker_name,
    c.crop_id,
    c.crop_type,
    cw.assigned_date,
    cw.task_role
FROM worker w
JOIN crop_worker cw ON cw.worker_id = w.worker_id
JOIN crop c ON c.crop_id = cw.crop_id;

CREATE OR REPLACE VIEW fertilizer_stock_view AS
SELECT
    fertilizer_id,
    fertilizer_type,
    stock_level,
    unit,
    CASE
        WHEN stock_level < 100 THEN 'LOW'
        ELSE 'OK'
    END AS stock_status
FROM fertilizer;

CREATE OR REPLACE VIEW harvest_summary_view AS
SELECT
    h.harvest_id,
    c.crop_type,
    h.harvest_date,
    h.quantity AS harvested_quantity,
    COALESCE(SUM(si.quantity_sold),0) AS sold_quantity,
    h.quantity - COALESCE(SUM(si.quantity_sold),0) AS remaining_quantity
FROM harvest h
JOIN crop c ON c.crop_id = h.crop_id
LEFT JOIN sale_item si ON si.harvest_id = h.harvest_id
GROUP BY h.harvest_id, c.crop_type, h.harvest_date, h.quantity;

CREATE OR REPLACE VIEW sales_summary_view AS
SELECT
    s.sale_id,
    s.invoice_number,
    s.sale_date,
    c.full_name AS customer,
    s.total_amount
FROM sale s
JOIN customer c ON c.customer_id = s.customer_id;

-- ---------- 10 ADVANCED SQL QUERIES ----------

-- Query 1: Total production by crop
SELECT c.crop_type, SUM(h.quantity) AS total_harvested
FROM crop c
JOIN harvest h ON h.crop_id = c.crop_id
GROUP BY c.crop_type
ORDER BY total_harvested DESC;

-- Query 2: Crops producing above the average harvest
SELECT c.crop_type, SUM(h.quantity) AS total_harvested
FROM crop c
JOIN harvest h ON h.crop_id = c.crop_id
GROUP BY c.crop_id, c.crop_type
HAVING SUM(h.quantity) > (
    SELECT AVG(total_quantity)
    FROM (
        SELECT SUM(quantity) AS total_quantity
        FROM harvest
        GROUP BY crop_id
    ) x
)
ORDER BY total_harvested DESC;

-- Query 3: Customer sales ranking using a window function
SELECT
    c.full_name,
    SUM(s.total_amount) AS total_spent,
    RANK() OVER (ORDER BY SUM(s.total_amount) DESC) AS sales_rank
FROM customer c
JOIN sale s ON s.customer_id = c.customer_id
GROUP BY c.customer_id, c.full_name
ORDER BY sales_rank;

-- Query 4: Monthly sales totals
SELECT
    DATE_TRUNC('month', sale_date)::date AS sales_month,
    SUM(total_amount) AS monthly_sales
FROM sale
GROUP BY DATE_TRUNC('month', sale_date)
ORDER BY sales_month;

-- Query 5: Workers assigned to more than one crop
SELECT
    w.employee_id,
    w.fname || ' ' || w.lname AS worker_name,
    COUNT(DISTINCT cw.crop_id) AS crop_count
FROM worker w
JOIN crop_worker cw ON cw.worker_id = w.worker_id
GROUP BY w.worker_id, w.employee_id, w.fname, w.lname
HAVING COUNT(DISTINCT cw.crop_id) > 1
ORDER BY crop_count DESC;

-- Query 6: Low fertilizer stock
SELECT fertilizer_type, stock_level, unit
FROM fertilizer
WHERE stock_level < 100
ORDER BY stock_level;

-- Query 7: Equipment currently unavailable
SELECT equipment_name, equipment_type, status
FROM equipment
WHERE status <> 'Available'
ORDER BY equipment_name;

-- Query 8: Harvest remaining after sales
SELECT *
FROM harvest_summary_view
WHERE remaining_quantity > 0
ORDER BY remaining_quantity DESC;

-- Query 9: Highest-value sales
SELECT
    s.invoice_number,
    c.full_name,
    s.total_amount,
    s.sale_date
FROM sale s
JOIN customer c ON c.customer_id = s.customer_id
WHERE s.total_amount > (
    SELECT AVG(total_amount) FROM sale
)
ORDER BY s.total_amount DESC;

-- Query 10: Crop production with worker count
SELECT
    c.crop_type,
    COALESCE(SUM(h.quantity),0) AS total_harvested,
    COUNT(DISTINCT cw.worker_id) AS workers_assigned
FROM crop c
LEFT JOIN harvest h ON h.crop_id = c.crop_id
LEFT JOIN crop_worker cw ON cw.crop_id = c.crop_id
GROUP BY c.crop_id, c.crop_type
ORDER BY total_harvested DESC;


