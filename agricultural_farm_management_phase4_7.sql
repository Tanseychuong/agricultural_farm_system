-- PHASE 4: PHYSICAL DESIGN / DDL


CREATE TABLE farm (
    farm_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_name        VARCHAR(100) NOT NULL UNIQUE,
    location         VARCHAR(150) NOT NULL,
    total_size       NUMERIC(10,2) NOT NULL CHECK (total_size > 0)
);

CREATE TABLE crop (
    crop_id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_id                 INTEGER NOT NULL,
    crop_type               VARCHAR(80) NOT NULL,
    planting_date           DATE NOT NULL,
    expected_harvest_date   DATE NOT NULL,
    status                  VARCHAR(20) NOT NULL DEFAULT 'Planned'
                            CHECK (status IN ('Planned','Growing','Harvested','Completed')),
    plot_number             VARCHAR(30) NOT NULL,
    CONSTRAINT fk_crop_farm FOREIGN KEY (farm_id) REFERENCES farm(farm_id),
    CONSTRAINT chk_crop_dates CHECK (expected_harvest_date >= planting_date),
    CONSTRAINT uq_farm_plot_crop UNIQUE (farm_id, plot_number)
);

CREATE TABLE worker (
    worker_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id     VARCHAR(20) NOT NULL UNIQUE,
    fname           VARCHAR(50) NOT NULL,
    lname           VARCHAR(50) NOT NULL,
    contact_details VARCHAR(100) NOT NULL,
    job_role        VARCHAR(60) NOT NULL,
    hire_date       DATE NOT NULL
);

CREATE TABLE equipment (
    equipment_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_name  VARCHAR(100) NOT NULL,
    equipment_type  VARCHAR(60) NOT NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'Available'
                    CHECK (status IN ('Available','In Use','Under Maintenance'))
);

CREATE TABLE fertilizer (
    fertilizer_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fertilizer_type VARCHAR(80) NOT NULL UNIQUE,
    stock_level     NUMERIC(10,2) NOT NULL CHECK (stock_level >= 0),
    unit            VARCHAR(20) NOT NULL
);

CREATE TABLE harvest (
    harvest_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_id         INTEGER NOT NULL,
    harvest_date    DATE NOT NULL,
    quantity        NUMERIC(10,2) NOT NULL CHECK (quantity > 0),
    CONSTRAINT fk_harvest_crop FOREIGN KEY (crop_id) REFERENCES crop(crop_id)
);

CREATE TABLE customer (
    customer_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name       VARCHAR(100) NOT NULL,
    contact_details VARCHAR(100) NOT NULL,
    address         VARCHAR(150) NOT NULL
);

CREATE TABLE sale (
    sale_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     INTEGER NOT NULL,
    sale_date       DATE NOT NULL,
    invoice_number  VARCHAR(30) NOT NULL UNIQUE,
    total_amount    NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    CONSTRAINT fk_sale_customer FOREIGN KEY (customer_id) REFERENCES customer(customer_id)
);

-- Worker <-> Crop
CREATE TABLE crop_worker (
    crop_worker_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_id         INTEGER NOT NULL,
    worker_id       INTEGER NOT NULL,
    assigned_date   DATE NOT NULL,
    task_role       VARCHAR(80) NOT NULL,
    CONSTRAINT fk_crop_worker_crop FOREIGN KEY (crop_id) REFERENCES crop(crop_id),
    CONSTRAINT fk_crop_worker_worker FOREIGN KEY (worker_id) REFERENCES worker(worker_id),
    CONSTRAINT uq_crop_worker UNIQUE (crop_id, worker_id, assigned_date)
);

-- Worker <-> Equipment
CREATE TABLE equipment_assignment (
    assignment_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id    INTEGER NOT NULL,
    worker_id       INTEGER NOT NULL,
    assigned_date   DATE NOT NULL,
    return_date     DATE,
    CONSTRAINT fk_equipment_assignment_equipment
        FOREIGN KEY (equipment_id) REFERENCES equipment(equipment_id),
    CONSTRAINT fk_equipment_assignment_worker
        FOREIGN KEY (worker_id) REFERENCES worker(worker_id),
    CONSTRAINT chk_equipment_dates
        CHECK (return_date IS NULL OR return_date >= assigned_date)
);

CREATE TABLE equipment_maintenance (
    maintenance_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id    INTEGER NOT NULL,
    maintenance_date DATE NOT NULL,
    description     VARCHAR(200) NOT NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'Completed'
                    CHECK (status IN ('Scheduled','Completed')),
    CONSTRAINT fk_maintenance_equipment
        FOREIGN KEY (equipment_id) REFERENCES equipment(equipment_id)
);

-- Fertilizer usage
CREATE TABLE fertilizer_usage (
    usage_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fertilizer_id   INTEGER NOT NULL,
    crop_id         INTEGER NOT NULL,
    quantity_used   NUMERIC(10,2) NOT NULL CHECK (quantity_used > 0),
    usage_date      DATE NOT NULL,
    CONSTRAINT fk_usage_fertilizer FOREIGN KEY (fertilizer_id) REFERENCES fertilizer(fertilizer_id),
    CONSTRAINT fk_usage_crop FOREIGN KEY (crop_id) REFERENCES crop(crop_id)
);

-- Worker <-> Harvest activity
CREATE TABLE harvest_worker (
    harvest_worker_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    harvest_id        INTEGER NOT NULL,
    worker_id         INTEGER NOT NULL,
    assigned_date     DATE NOT NULL,
    task_role         VARCHAR(80) NOT NULL,
    CONSTRAINT fk_harvest_worker_harvest FOREIGN KEY (harvest_id) REFERENCES harvest(harvest_id),
    CONSTRAINT fk_harvest_worker_worker FOREIGN KEY (worker_id) REFERENCES worker(worker_id),
    CONSTRAINT uq_harvest_worker UNIQUE (harvest_id, worker_id)
);

-- Sale <-> Harvest
CREATE TABLE sale_item (
    sale_item_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id         INTEGER NOT NULL,
    harvest_id      INTEGER NOT NULL,
    quantity_sold   NUMERIC(10,2) NOT NULL CHECK (quantity_sold > 0),
    unit_price      NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    CONSTRAINT fk_sale_item_sale FOREIGN KEY (sale_id) REFERENCES sale(sale_id),
    CONSTRAINT fk_sale_item_harvest FOREIGN KEY (harvest_id) REFERENCES harvest(harvest_id)
);

-- Useful indexes only
CREATE INDEX idx_crop_farm ON crop(farm_id);
CREATE INDEX idx_crop_status ON crop(status);
CREATE INDEX idx_harvest_crop ON harvest(crop_id);
CREATE INDEX idx_harvest_date ON harvest(harvest_date);
CREATE INDEX idx_sale_customer ON sale(customer_id);
CREATE INDEX idx_sale_date ON sale(sale_date);
CREATE INDEX idx_fertilizer_usage_crop ON fertilizer_usage(crop_id);
CREATE INDEX idx_equipment_status ON equipment(status);
CREATE INDEX idx_crop_worker_worker ON crop_worker(worker_id);
CREATE INDEX idx_sale_item_harvest ON sale_item(harvest_id);


